#!/usr/bin/env node
// Üçüncü taraf lisansları → resources/licenses/THIRD-PARTY.txt (pakete girer).
// Kaynaklar: `cargo metadata` (uygulama crate'inin normal bağımlılıkları; paketlenen hedefler: Mac + Windows) ve web'in
// üretim bağımlılıkları (node_modules içinde `dependencies` zinciri). Her paketin kendi LICENSE/NOTICE dosyası olduğu
// gibi alınır; aynı metin bir kez yazılır, altında onu kullanan paketler listelenir.
// Elle: node apps/desktop/src-tauri/scripts/licenses.mjs   (bağımlılık değişince çalıştır, çıktıyı commit et)
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tauriDir = resolve(here, '..')
const webDir = resolve(tauriDir, '../web')
const out = join(tauriDir, 'resources/licenses/THIRD-PARTY.txt')

const LICENSE_FILE = /^(licen[cs]e|copying|notice|copyright)([-._].*)?$/i

function licenseTexts(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => {
      try {
        return readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()
      } catch {
        return ''
      }
    })
    .filter(Boolean)
}

// ---------------------------------------------------------------- Rust
const TARGETS = ['aarch64-apple-darwin', 'x86_64-apple-darwin', 'x86_64-pc-windows-msvc', 'aarch64-pc-windows-msvc']

function rustPackages() {
  const all = new Map()
  for (const t of TARGETS) for (const p of rustPackagesFor(t)) all.set(`${p.name}@${p.version}`, p)
  return [...all.values()]
}

function rustPackagesFor(target) {
  const meta = JSON.parse(
    execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', target], {
      cwd: tauriDir,
      maxBuffer: 256 * 1024 * 1024,
    }).toString(),
  )
  const byId = new Map(meta.packages.map((p) => [p.id, p]))
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
  const root = meta.packages.find((p) => p.name === 'kaans-terminal')
  if (!root) throw new Error('kaans-terminal crate bulunamadı')
  const seen = new Set()
  const stack = [root.id]
  while (stack.length) {
    const id = stack.pop()
    for (const d of nodes.get(id)?.deps ?? []) {
      // yalnızca normal bağımlılıklar (build/dev hariç); hedef süzmesini --filter-platform yapar
      if (!d.dep_kinds.some((k) => k.kind === null)) continue
      if (seen.has(d.pkg)) continue
      seen.add(d.pkg)
      stack.push(d.pkg)
    }
  }
  return [...seen]
    .map((id) => byId.get(id))
    .filter((p) => p && p.source) // workspace üyeleri (bizim kodumuz) hariç
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? 'see file' : 'unknown'),
      texts: licenseTexts(dirname(p.manifest_path)),
    }))
}

// ---------------------------------------------------------------- web (npm)
function npmPackages() {
  const rootPkg = JSON.parse(readFileSync(join(webDir, 'package.json'), 'utf8'))
  const found = new Map()
  // Node'un çözümleme kuralı: önce bağımlı paketin kendi node_modules'u, sonra yukarı doğru.
  function locate(name, fromDir) {
    let dir = fromDir
    for (;;) {
      const p = join(dir, 'node_modules', name)
      if (existsSync(join(p, 'package.json'))) return p
      if (dir === webDir || dir === dirname(dir)) return null
      dir = dirname(dir)
      if (!dir.startsWith(webDir)) return null
    }
  }
  function walk(deps, fromDir) {
    for (const name of Object.keys(deps ?? {})) {
      const dir = locate(name, fromDir)
      if (!dir || found.has(dir)) continue
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
      const lic = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'unknown')
      found.set(dir, { name: pkg.name, version: pkg.version, license: lic, texts: licenseTexts(dir) })
      walk(pkg.dependencies, dir)
    }
  }
  walk(rootPkg.dependencies, webDir)
  return [...found.values()]
}

// ---------------------------------------------------------------- çıktı
function render(sections) {
  const lines = [
    "Kaan's Terminal — third-party software notices",
    '=============================================',
    '',
    "Kaan's Terminal is MIT licensed (see LICENSE). It includes the open-source components listed below.",
    'Each component is the property of its respective authors and is used under its own license.',
    'Also bundled: Space Grotesk (SIL OFL 1.1, SpaceGrotesk-OFL.txt), rtk-oss (Apache-2.0, rtk-LICENSE).',
    'Generated by apps/desktop/src-tauri/scripts/licenses.mjs.',
    '',
  ]
  for (const [title, pkgs] of sections) {
    pkgs.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
    lines.push('', `## ${title} (${pkgs.length})`, '')
    for (const p of pkgs) lines.push(`${p.name} ${p.version}  —  ${p.license}`)
  }
  // Aynı lisans metni bir kez
  const byText = new Map()
  for (const [, pkgs] of sections)
    for (const p of pkgs)
      for (const t of p.texts) {
        const list = byText.get(t) ?? []
        list.push(`${p.name} ${p.version}`)
        byText.set(t, list)
      }
  lines.push('', '', '## License texts', '')
  for (const [text, users] of byText) {
    lines.push('-'.repeat(78), `Used by: ${[...new Set(users)].join(', ')}`, '', text, '')
  }
  const missing = sections.flatMap(([, p]) => p).filter((p) => !p.texts.length)
  if (missing.length) {
    lines.push('-'.repeat(78), 'Components without a bundled license file (license per their metadata above):')
    for (const p of missing) lines.push(`  ${p.name} ${p.version} — ${p.license}`)
  }
  return lines.join('\n') + '\n'
}

const rust = rustPackages()
const web = npmPackages()
writeFileSync(out, render([['Rust crates', rust], ['Web (npm) packages', web]]))
const unknown = [...rust, ...web].filter((p) => p.license === 'unknown')
console.log(`THIRD-PARTY.txt: ${rust.length} crates, ${web.length} npm packages${unknown.length ? `, unknown license: ${unknown.map((p) => p.name).join(', ')}` : ''}`)
